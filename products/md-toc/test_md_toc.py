#!/usr/bin/env python3
"""Tests for md-toc.py — run with: python3 test_md_toc.py"""
import json
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
TOOL = os.path.join(HERE, "md-toc.py")


def run(*args, stdin=None):
    return subprocess.run(
        [sys.executable, TOOL] + list(args),
        capture_output=True, text=True,
        input=stdin,
    )


def expect(cond, msg):
    if not cond:
        print(f"FAIL: {msg}")
        sys.exit(1)
    print(f"ok: {msg}")


def tmp_file(content, ext=".md"):
    f = tempfile.NamedTemporaryFile(suffix=ext, delete=False, mode="w")
    f.write(content)
    f.close()
    return f.name


def main():
    # 1. basic headings
    f = tmp_file("# Title\n\n## Alpha\n\n## Beta\n")
    r = run(f)
    expect(r.returncode == 0, "basic exits 0")
    expect("- [Alpha](#alpha)" in r.stdout, "alpha link present")
    expect("- [Beta](#beta)" in r.stdout, "beta link present")
    os.unlink(f)

    # 2. max-depth default 2 (H3 excluded by default)
    f = tmp_file("# T\n\n## A\n\n### Deep\n")
    r = run(f)
    expect("- [A](#a)" in r.stdout, "H2 included")
    expect("Deep" not in r.stdout, "H3 excluded by default max-depth 2")
    os.unlink(f)

    # 3. max-depth 3 includes H3
    f = tmp_file("# T\n\n## A\n\n### Deep\n")
    r = run(f, "--max-depth", "3")
    expect("Deep" in r.stdout, "H3 included with max-depth 3")
    os.unlink(f)

    # 4. code fence headings ignored
    f = tmp_file("# T\n\n```\n## NotAHeading\n```\n\n## Real\n")
    r = run(f)
    expect("NotAHeading" not in r.stdout, "fenced heading ignored")
    expect("Real" in r.stdout, "real heading present")
    os.unlink(f)

    # 5. duplicate anchors numbered
    f = tmp_file("# T\n\n## Foo\n\n## Foo\n\n## Foo\n")
    r = run(f, "--max-depth", "2", "--json")
    data = json.loads(r.stdout)
    anchors = [d["anchor"] for d in data]
    expect(anchors == ["t", "foo", "foo-1", "foo-2"], f"dup anchors {anchors}")
    os.unlink(f)

    # 6. slugify punctuation
    f = tmp_file("# T\n\n## Hello, World!\n")
    r = run(f, "--json")
    data = json.loads(r.stdout)
    anchors = {d["text"]: d["anchor"] for d in data}
    expect(anchors.get("Hello, World!") == "hello-world", f"slug {anchors}")

    # 7. front matter skipped by default
    f = tmp_file("---\ntitle: X\n---\n\n# T\n\n## A\n")
    r = run(f)
    expect("title" not in r.stdout.lower() or "title: x" not in r.stdout, "front matter not treated as heading")
    expect("A" in r.stdout, "real heading present")
    os.unlink(f)

    # 8. --no-front-matter treats front-matter lines as content
    f = tmp_file("---\ntitle: X\n## Hidden\n---\n\n# T\n\n## A\n")
    r = run(f)
    expect("Hidden" not in r.stdout, "front-matter heading skipped by default")
    r = run(f, "--no-front-matter")
    expect(r.returncode == 0, "no-front-matter exits 0")
    expect("Hidden" in r.stdout, "no-front-matter parses front-matter heading")
    os.unlink(f)

    # 9. json output
    f = tmp_file("# T\n\n## A\n")
    r = run(f, "--json")
    expect(r.returncode == 0, "json exits 0")
    data = json.loads(r.stdout)
    expect(isinstance(data, list), "json is list")
    os.unlink(f)

    # 10. missing file
    r = run("/nonexistent/file.md")
    expect(r.returncode == 1, "missing file returns non-zero")

    # 11. insert mode
    f = tmp_file("# T\n\n## A\n")
    r = run(f, "--insert")
    expect(r.returncode == 0, "insert exits 0")
    content = open(f).read()
    expect("<!-- TOC: generated by md-toc -->" in content, "toc inserted")
    expect("- [A](#a)" in content, "inserted entry")
    os.unlink(f)

    # 12. idempotent insert (no double block)
    f = tmp_file("# T\n\n## A\n")
    run(f, "--insert")
    run(f, "--insert")
    content = open(f).read()
    expect(content.count("<!-- TOC: generated by md-toc -->") == 1, "idempotent insert")
    os.unlink(f)

    print("ALL TESTS PASS")


if __name__ == "__main__":
    main()
